// ---------- کمک‌کارها ----------
function baseDeck() {
  const p = new pptxgen();
  p.defineLayout({ name: 'W', width: 13.33, height: 7.5 });
  p.layout = 'W';
  return p;
}
const isFa = t => /[\u0600-\u06FF]/.test(t);
const dir = t => (isFa(t) ? { rtlMode: true, align: 'right' } : { rtlMode: false, align: 'left' });
const txt = (s, t, o = {}) => s.addText(t, { fontFace: FONT, color: INK, ...dir(t), ...o });

//  اسلاید تیتر
function cover(p, kicker, title, sub) {
  const s = p.addSlide();
  s.background = { color: NAVY };
  s.addShape('rect', { x: 0, y: 0, w: 13.33, h: 0.18, fill: { color: GOLD } });
  txt(s, kicker, { x: 0.9, y: 1.55, w: 11.5, h: 0.6, fontSize: 15, color: SOFT });
  txt(s, title, { x: 0.9, y: 2.15, w: 11.5, h: 1.4, fontSize: 38, bold: true, color: WHT });
  txt(s, sub, { x: 0.9, y: 3.65, w: 11.5, h: 0.55, fontSize: 16, color: SOFT });
  txt(s, 'آشنایی با مفاهیم هوش مصنوعی • کارگاه ۱', { x: 0.9, y: 6.35, w: 11.5, h: 0.5, fontSize: 12, color: '8FA3BF' });
  return s;
}

//  قاب مشترک اسلایدهای محتوا: عنوان + کادر + ردپا
function content(p, title, opts = {}) {
  const s = p.addSlide();
  s.background = { color: WHT };
  s.addShape('rect', { x: 12.33, y: 0.42, w: 0.08, h: 0.62, fill: { color: ACC } }); // نوار لهجه سمت راست عنوان
  txt(s, title, { x: 0.6, y: 0.32, w: 11.55, h: 0.78, fontSize: 26, bold: true, color: NAVY });
  if (opts.sub) txt(s, opts.sub, { x: 0.6, y: 1.06, w: 11.6, h: 0.4, fontSize: 13, color: MUT });
  return s;
}
function footers(p, sessionLine) {
  p.slides.forEach((s, i) => {
    if (i === 0) return;
    txt(s, sessionLine, { x: 6, y: 7.06, w: 6.9, h: 0.36, fontSize: 10, color: MUT });
    txt(s, `${fa(i + 1)} از ${fa(p.slides.length)}`, { x: 0.35, y: 7.06, w: 2.2, h: 0.36, fontSize: 10, color: MUT, rtlMode: true, align: 'left' });
  });
}

const FA = '۰۱۲۳۴۵۶۷۸۹';
const fa = n => String(n).replace(/\d/g, d => FA[d]);

//  گلوله‌ها: آیتم = متن یا [متن، سطح]  —  rtlMode باید روی خودِ هر آیتم باشد، نه فقط قاب
function bullets(s, items, o = {}) {
  const { x = 0.6, y = 1.35, w = 12.1, fontSize = 17, gap = 10, noBullet = false } = o;
  s.addText(items.map(it => {
    const [t, lvl = 0] = Array.isArray(it) ? it : [it, 0];
    return { text: t, options: { fontFace: FONT, fontSize: lvl ? fontSize - 3 : fontSize, color: lvl ? MUT : INK, rtlMode: true, align: 'right', ...(noBullet ? {} : { bullet: { code: '2022', indent: 10 } }), paraSpaceAfter: gap, indentLevel: lvl } };
  }), { x, y, w, h: 7.0 - y - 0.55, rtlMode: true, align: 'right', valign: 'top', lineSpacing: 26 });
}
//  یادداشت سخنران (speaker notes)
function note(s, text) {
  if (text) s.addNotes(text);
}

//  کارت‌ها از راست به چپ
function cardsRTL(s, defs, o = {}) {
  const { y = 1.6, h = 3.4, x0 = 0.6, x1 = 12.73, gap = 0.25, titleColor = NAVY } = o;
  const w = (x1 - x0 - gap * (defs.length - 1)) / defs.length;
  defs.forEach((d, i) => {
    const x = x1 - (i + 1) * w - i * gap; // اولین کارت در راست‌ترین جایگاه
    s.addShape('roundRect', { x, y, w, h, rectRadius: 0.09, fill: { color: LIGHT }, line: { color: SOFT, width: 1 } });
    s.addShape('rect', { x: x + w - 0.1, y: y + 0.25, w: 0.06, h: 0.5, fill: { color: ACC } });
    txt(s, d.t, { x: x + 0.25, y: y + 0.22, w: w - 0.55, h: 0.65, fontSize: 17, bold: true, color: titleColor });
    txt(s, d.b, { x: x + 0.25, y: y + 0.95, w: w - 0.55, h: h - 1.15, fontSize: 12.5, color: INK, rtlMode: true, align: 'right', valign: 'top', lineSpacing: 22 });
  });
}

//  جدول راست‌چین (ستون‌ها را ورودیِ LTR می‌دهیم و این‌جا برمی‌گردانیم)
function tableRTL(s, head, rows, o = {}) {
  const { x = 0.6, y = 1.5, w = 12.1, colW, fontSize = 13 } = o;
  const headRow = [...head].reverse().map(t => ({ text: t, options: { fill: { color: NAVY }, color: WHT, bold: true, rtlMode: true, align: 'right' } }));
  const bodyRows = rows.map((r, ri) => [...r].reverse().map(t => {
    const faT = isFa(t);
    return { text: t, options: { fill: { color: ri % 2 ? LIGHT : WHT }, color: INK, rtlMode: faT, align: faT ? 'right' : 'center' } };
  }));
  s.addTable([headRow, ...bodyRows], {
    x, y, w, ...(colW ? { colW: [...colW].reverse() } : { colW: head.map(() => w / head.length) }),
    fontFace: FONT, fontSize, color: INK, border: { pt: 0.75, color: SOFT }, align: 'center', valign: 'middle',
    rtlMode: true, margin: [4, 8, 4, 8], rowH: 0.52,
  });
}

function pic(s, file, o = {}) {
  s.addImage({ path: path.join(ASSETS, file), ...o });
}

